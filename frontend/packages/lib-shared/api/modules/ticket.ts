import type { CordysAxios } from '@lib/shared/api/http/Axios';

import {
  AccountTicketPageUrl,
  TicketAddUrl,
  TicketAssignUrl,
  TicketConfigSaveUrl,
  TicketConfigUrl,
  TicketDeleteUrl,
  TicketFollowUrl,
  TicketFormUrl,
  TicketGetUrl,
  TicketInternalReplyUrl,
  TicketOptionsUrl,
  TicketPageUrl,
  TicketPriorityUrl,
  TicketPublicAddUrl,
  TicketPublicSatisfyLookupUrl,
  TicketPublicSatisfyUrl,
  TicketPurgeUrl,
  TicketRecoverUrl,
  TicketReplyUrl,
  TicketRestartUrl,
  TicketRouteDeleteUrl,
  TicketRouteListUrl,
  TicketRouteSaveUrl,
  TicketSatisfyUrl,
  TicketStatusDeleteUrl,
  TicketStatusListUrl,
  TicketStatusSaveUrl,
  TicketStatusSortUrl,
  TicketStatusUrl,
  TicketTemplateDeleteUrl,
  TicketTemplateListUrl,
  TicketTemplateSaveUrl,
  TicketUpdateUrl,
  TicketUrgeUrl,
} from '../requrls/ticket';

export default function useTicketApi(CDR: CordysAxios) {
  return {
    pageTicket: (data: Record<string, unknown>) => CDR.post({ url: TicketPageUrl, data }),
    pageAccountTicket: (data: Record<string, unknown>) => CDR.post({ url: AccountTicketPageUrl, data }),
    publishPublicTicket: (data: Record<string, unknown>) =>
      CDR.post({ url: TicketPublicAddUrl, data }, { withToken: false }),
    lookupPublicSatisfy: (data: Record<string, unknown>) =>
      CDR.post({ url: TicketPublicSatisfyLookupUrl, data }, { withToken: false }),
    submitPublicSatisfy: (data: Record<string, unknown>) =>
      CDR.post({ url: TicketPublicSatisfyUrl, data }, { withToken: false }),
    getTicket: (id: string) => CDR.get({ url: `${TicketGetUrl}/${id}` }),
    addTicket: (data: Record<string, unknown>) => CDR.post({ url: TicketAddUrl, data }),
    updateTicket: (data: Record<string, unknown>) => CDR.post({ url: TicketUpdateUrl, data }),
    replyTicket: (data: Record<string, unknown>) => CDR.post({ url: TicketReplyUrl, data }),
    internalReplyTicket: (data: Record<string, unknown>) => CDR.post({ url: TicketInternalReplyUrl, data }),
    changeTicketStatus: (data: Record<string, unknown>) => CDR.post({ url: TicketStatusUrl, data }),
    changeTicketPriority: (data: Record<string, unknown>) => CDR.post({ url: TicketPriorityUrl, data }),
    assignTicket: (data: Record<string, unknown>) => CDR.post({ url: TicketAssignUrl, data }),
    urgeTicket: (data: Record<string, unknown>) => CDR.post({ url: TicketUrgeUrl, data }),
    followTicket: (data: Record<string, unknown>) => CDR.post({ url: TicketFollowUrl, data }),
    restartTicket: (id: string) => CDR.post({ url: TicketRestartUrl, data: { id } }),
    satisfyTicket: (data: Record<string, unknown>) => CDR.post({ url: TicketSatisfyUrl, data }),
    recycleTicket: (id: string) => CDR.get({ url: `${TicketDeleteUrl}/${id}` }),
    recoverTicket: (ids: string[]) => CDR.post({ url: TicketRecoverUrl, data: { ids } }),
    purgeTicket: (ids: string[]) => CDR.post({ url: TicketPurgeUrl, data: { ids } }),
    getTicketForm: () => CDR.get({ url: TicketFormUrl }),
    getTicketOptions: () => CDR.get({ url: TicketOptionsUrl }),
    listTicketTemplate: () => CDR.get({ url: TicketTemplateListUrl }),
    saveTicketTemplate: (data: Record<string, unknown>) => CDR.post({ url: TicketTemplateSaveUrl, data }),
    deleteTicketTemplate: (id: string) => CDR.get({ url: `${TicketTemplateDeleteUrl}/${id}` }),
    listTicketStatusConfig: () => CDR.get({ url: TicketStatusListUrl }),
    saveTicketStatusConfig: (data: Record<string, unknown>) => CDR.post({ url: TicketStatusSaveUrl, data }),
    sortTicketStatusConfig: (ids: string[]) => CDR.post({ url: TicketStatusSortUrl, data: { ids } }),
    deleteTicketStatusConfig: (id: string) => CDR.get({ url: `${TicketStatusDeleteUrl}/${id}` }),
    listTicketRoute: () => CDR.get({ url: TicketRouteListUrl }),
    saveTicketRoute: (data: Record<string, unknown>) => CDR.post({ url: TicketRouteSaveUrl, data }),
    deleteTicketRoute: (id: string) => CDR.get({ url: `${TicketRouteDeleteUrl}/${id}` }),
    getTicketConfig: () => CDR.get({ url: TicketConfigUrl }),
    saveTicketConfig: (data: Record<string, unknown>) => CDR.post({ url: TicketConfigSaveUrl, data }),
  };
}
