/** 与 Java role.* 文案一致，内置角色在列表里显示中文名。 */
export const INTERNAL_ROLE_NAMES: Record<string, string> = {
  org_admin: '管理员',
  sales_manager: '销售经理',
  sales_staff: '销售专员',
};

export function translateRoleName(name: string, internal: boolean): string {
  if (!internal) {
    return name;
  }
  return INTERNAL_ROLE_NAMES[name] ?? name;
}
